/** Data/hora (ISO) de "n" minutos atrás. */
function minutesAgo(n) {
  return new Date(Date.now() - n * 60_000).toISOString();
}

/** Monta um veículo com os valores padrão (campos opcionais vazios). */
function vehicle(data) {
  return {
    draft: false,
    photoUrl: null,
    transmission: "",
    chassis: "",
    openOrder: null,
    box: null,
    servicesCount: 0,
    lastService: null,
    nextReviewKm: null,
    nextReviewDate: null,
    updatedAt: minutesAgo(42),
    updatedBy: currentOperator,
    ...data,
  };
}

