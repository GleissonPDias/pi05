import { toISODate } from "../utils/dates";
import { currentOperator } from "./user";

/** Data (AAAA-MM-DD) de "n" dias atrás, para os dados fictícios nunca ficarem velhos. */
function daysAgo(n) {
  const date = new Date();
  date.setDate(date.getDate() - n);
  return toISODate(date);
}

/** Data/hora (ISO) de "n" dias atrás às 16:42. */
function dateTimeAgo(n) {
  const date = new Date();
  date.setDate(date.getDate() - n);
  date.setHours(16, 42, 0, 0);
  return date.toISOString();
}

